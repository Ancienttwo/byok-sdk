// Generates `packages/keys/src/pi-model-catalog.generated.ts` from the pi-ai
// that `@byok-sdk/client` pins (`dependencies` and `byok.piRuntimePin`).
//
// Keys has no pi-ai dependency, at run time or for its tests: it carries the
// generated table only. The pinned copy is read through the client's
// node_modules link, and its version must equal both client pins. Each entry is
// classified by keys' own `classifyPiCatalogModel`, so the table and the
// profile schema apply one admission rule.
//
// Usage:
//   bun scripts/keys/generate-pi-model-catalog.ts          # rewrite the file
//   bun scripts/keys/generate-pi-model-catalog.ts --check  # exit 1 on drift
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { classifyPiCatalogModel } from '../../packages/keys/src/pi-model-catalog';
import { PI_MODEL_APIS } from '../../packages/keys/src/pi-model-config';
import { MODEL_PROVIDER_VENDORS } from '../../packages/keys/src/provider-catalog';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const PI_MODEL_CATALOG_FILE = path.join(repoRoot, 'packages/keys/src/pi-model-catalog.generated.ts');
const PI_AI = '@earendil-works/pi-ai';

interface PinnedPiAi {
  readonly version: string;
  readonly root: string;
}

/** The pi-ai package directory the client resolves, after checking it is the pinned version. */
export function pinnedPiAi(): PinnedPiAi {
  const client = JSON.parse(readFileSync(path.join(repoRoot, 'packages/client/package.json'), 'utf8'));
  const pin = client.byok?.piRuntimePin;
  if (client.dependencies?.[PI_AI] !== pin) {
    throw new Error(`packages/client/package.json: ${PI_AI} ${String(client.dependencies?.[PI_AI])} is not byok.piRuntimePin ${String(pin)}`);
  }
  const root = realpathSync(path.join(repoRoot, 'packages/client/node_modules', PI_AI));
  const version = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8')).version;
  if (version !== pin) throw new Error(`installed ${PI_AI} ${String(version)} is not the pinned ${String(pin)}; run bun install`);
  return { version, root };
}

/** Locale-independent order, so Bun and Node render the same bytes on every machine. */
function compareCodeUnits(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

async function importPiAi<T>(root: string, subpath: string): Promise<T> {
  return import(pathToFileURL(path.join(root, 'dist', `${subpath}.js`)).href) as Promise<T>;
}

/** The generated module text for the pinned pi-ai. */
export async function renderPiModelCatalog(): Promise<string> {
  const piAi = pinnedPiAi();
  const { getBuiltinModels } = await importPiAi<{ getBuiltinModels(provider: string): Record<string, unknown>[] }>(
    piAi.root, 'providers/all');
  const { MODEL_THINKING_LEVELS } = await importPiAi<{ MODEL_THINKING_LEVELS: readonly string[] }>(
    piAi.root, 'providers/model-schema');

  const providerLines: string[] = [];
  for (const provider of Object.keys(MODEL_PROVIDER_VENDORS).sort()) {
    const { adapter } = MODEL_PROVIDER_VENDORS[provider as keyof typeof MODEL_PROVIDER_VENDORS];
    const byApi = new Map<string, string[]>();
    const models = getBuiltinModels(provider)
      .filter((model) => (PI_MODEL_APIS as readonly unknown[]).includes(model.api))
      .sort((left, right) => compareCodeUnits(String(left.id), String(right.id)));
    for (const model of models) {
      const line = `      ${JSON.stringify(model.id)}: ${JSON.stringify(classifyPiCatalogModel(model, adapter))},`;
      byApi.set(String(model.api), [...(byApi.get(String(model.api)) ?? []), line]);
    }
    if (byApi.size === 0) continue;
    providerLines.push(`  ${JSON.stringify(provider)}: {`);
    for (const api of [...byApi.keys()].sort()) {
      providerLines.push(`    ${JSON.stringify(api)}: {`, ...byApi.get(api)!, '    },');
    }
    providerLines.push('  },');
  }

  return [
    `// Generated by scripts/keys/generate-pi-model-catalog.ts from ${PI_AI} ${piAi.version}. Do not edit.`,
    '// Regenerate with `bun scripts/keys/generate-pi-model-catalog.ts`; a client test fails on drift.',
    "import type { PiModelCatalogTable } from './pi-model-catalog';",
    '',
    '/** The pi-ai version this table and the thinking levels were generated from. */',
    `export const PI_MODEL_CATALOG_PI_AI_VERSION = ${JSON.stringify(piAi.version)};`,
    '',
    "/** Pi's `MODEL_THINKING_LEVELS`, in Pi's order. */",
    `export const PI_THINKING_LEVELS = ${JSON.stringify(MODEL_THINKING_LEVELS).replaceAll(',', ', ')} as const;`,
    '',
    '/** Every chat model of each vendor in `MODEL_PROVIDER_VENDORS`, for the Pi apis a profile projects. */',
    'export const PI_MODEL_CATALOG: PiModelCatalogTable = {',
    ...providerLines,
    '};',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const rendered = await renderPiModelCatalog();
  const relative = path.relative(repoRoot, PI_MODEL_CATALOG_FILE);
  if (process.argv.includes('--check')) {
    if (readFileSync(PI_MODEL_CATALOG_FILE, 'utf8').replaceAll('\r\n', '\n') !== rendered) {
      console.error(`${relative} is stale; run bun scripts/keys/generate-pi-model-catalog.ts`);
      process.exit(1);
    }
    console.log(`${relative} matches the pinned pi-ai`);
  } else {
    writeFileSync(PI_MODEL_CATALOG_FILE, rendered);
    console.log(`wrote ${relative}`);
  }
}
