import { randomUUID } from 'node:crypto';
import { promises as fsp } from 'node:fs';
import path from 'node:path';
import { acquirePathMutationGate, PathMutationGateBusyError } from '../util/path-mutation-gate';
import type { ServiceProgram } from './service-types';

/**
 * Every unit this SDK generates carries this text (an XML comment in a
 * plist or WinSW descriptor, a `#` comment in a systemd unit). It is the
 * only ownership evidence `inspect()` accepts: a file at our unit path
 * without it is `foreign` and never changed, unless the operator passes
 * `install({ replaceUnmarked: true })`.
 */
export const SERVICE_UNIT_MARKER = 'byok-sdk-service-unit: generated by @byok-sdk/client; repair() reverts local edits';

/**
 * How an installed unit compares with the one this definition generates (#1097):
 *
 * - `absent`: no unit file at the unit path.
 * - `exact`: the unit and its launcher match byte for byte.
 * - `repairable`: the unit carries {@link SERVICE_UNIT_MARKER} but it, or
 *   its launcher, differs. `repair()` and `install()` rewrite both.
 * - `foreign`: a unit file without the marker. Nothing changes it.
 */
export type ServiceUnitState = 'absent' | 'exact' | 'repairable' | 'foreign';

export interface ServiceUnitInspection {
  state: ServiceUnitState;
  /** The plist, systemd unit or WinSW descriptor. */
  unitPath: string;
  /** The stable launcher the unit runs (macOS and Linux); on Windows the SCM runs the installed WinSW executable. */
  launcherPath: string;
  /** The lifecycle owner recorded in the store, when one is. */
  owner?: string;
}

export type ServiceRepairResult =
  | { status: 'repaired' }
  | { status: 'not-needed'; state: 'exact' | 'absent' };

const ERROR_MESSAGES = {
  service_unit_unmarked: 'A service unit this SDK did not generate exists at the unit path. Re-run install with replaceUnmarked (CLI: --replace-unmarked) to replace it, or remove it with the tool that installed it.',
  lifecycle_owner_conflict: 'Another lifecycle owner of this product manages autostart. Uninstall through that owner first.',
  lifecycle_owner_unreadable: 'The lifecycle owner record in the store cannot be read; preserve it for inspection.',
  lifecycle_owner_busy: 'Another service lifecycle operation or local-state relocation is in progress. Run it again when that one has finished.',
  invalid_owner: 'The lifecycle owner must be 1-32 characters: lowercase letters, digits and "-", starting with a letter or digit.',
  service_unload_timeout: 'The service manager did not finish unloading the stopped service in time. Check the service manager, then run the operation again.',
} as const;

export type ServiceUnitErrorCode = keyof typeof ERROR_MESSAGES;

/** Closed codes only; the message never carries a path or OS text. */
export class ServiceUnitError extends Error {
  constructor(readonly code: ServiceUnitErrorCode) {
    super(ERROR_MESSAGES[code]);
    this.name = 'ServiceUnitError';
  }
}

const OWNER_PATTERN = /^[a-z0-9][a-z0-9-]{0,31}$/u;

export function assertServiceOwner(owner: unknown): asserts owner is string {
  if (typeof owner !== 'string' || !OWNER_PATTERN.test(owner)) throw new ServiceUnitError('invalid_owner');
}

/** `<storeDir>/service`: the SDK-owned directory for the launcher and the lifecycle owner record. */
export function serviceStateDir(storeDir: string, platform: NodeJS.Platform = process.platform): string {
  return (platform === 'win32' ? path.win32 : path.posix).join(storeDir, 'service');
}

/** The stable launcher path a macOS or Linux unit runs. */
export function serviceLauncherPath(storeDir: string, serviceName: string, platform: NodeJS.Platform = process.platform): string {
  return (platform === 'win32' ? path.win32 : path.posix).join(serviceStateDir(storeDir, platform), `${serviceName}.launcher.sh`);
}

function hasControlChar(value: string): boolean {
  for (let i = 0; i < value.length; i += 1) {
    const code = value.charCodeAt(i);
    if (code < 32 || code === 127) return true;
  }
  return false;
}

function shellQuote(value: string): string {
  if (hasControlChar(value)) {
    throw new Error(`service launcher values must not contain control characters (got ${JSON.stringify(value)})`);
  }
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * The POSIX launcher every macOS and Linux unit runs. The unit names only
 * this file, so a new program (a moved binary, a new Node, a new `current`)
 * rewrites the launcher and never the unit. It sets no environment:
 * `byok-agent start --service` captures the login-shell environment at
 * start (#392).
 */
export function generateServiceLauncher(program: ServiceProgram): string {
  const lines = ['#!/bin/sh', `# ${SERVICE_UNIT_MARKER}`];
  if (program.cwd !== undefined) lines.push(`cd ${shellQuote(program.cwd)} || exit 1`);
  lines.push(`exec ${[program.command, ...program.args].map(shellQuote).join(' ')}`);
  return `${lines.join('\n')}\n`;
}

export interface ServiceUnitFile {
  path: string;
  content: string;
  mode?: number;
}

export type ServiceUnitFs = Pick<typeof fsp, 'readFile'>;

async function readOptional(fs: ServiceUnitFs, file: string): Promise<string | undefined> {
  try {
    return await fs.readFile(file, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException)?.code === 'ENOENT') return undefined;
    throw error;
  }
}

/** Compares the installed files with `expected`; `expected[0]` is the unit. */
export async function classifyServiceUnit(fs: ServiceUnitFs, expected: readonly ServiceUnitFile[]): Promise<ServiceUnitState> {
  const [unit, ...rest] = expected;
  if (!unit) throw new Error('classifyServiceUnit requires the unit file');
  const installed = await readOptional(fs, unit.path);
  if (installed === undefined) return 'absent';
  if (!installed.includes(SERVICE_UNIT_MARKER)) return 'foreign';
  if (installed !== unit.content) return 'repairable';
  for (const file of rest) {
    if ((await readOptional(fs, file.path)) !== file.content) return 'repairable';
  }
  return 'exact';
}

const OWNER_RECORD_FILENAME = 'lifecycle-owner.json';

interface OwnerRecord {
  version: 1;
  owner: string;
  service: string;
}

export interface ServiceLifecycleOwnerInput {
  storeDir: string;
  /** Who sets autostart for this product, e.g. `cli` or `app`. */
  owner: string;
  /** The service name the owner registers. */
  service: string;
}

export type ServiceOwnerFs = Pick<typeof fsp, 'readFile' | 'writeFile' | 'rename' | 'rm' | 'mkdir'>;

function ownerRecordPath(storeDir: string): string {
  return path.join(serviceStateDir(storeDir), OWNER_RECORD_FILENAME);
}

/**
 * The lifecycle owner recorded for this product's store (#1097): the one
 * party (the CLI, or the product's App) that sets autostart. Undefined when
 * no owner holds it.
 */
export async function readServiceLifecycleOwner(storeDir: string, fs: ServiceOwnerFs = fsp): Promise<{ owner: string; service: string } | undefined> {
  let text: string | undefined;
  try {
    text = await readOptional(fs, ownerRecordPath(storeDir));
  } catch {
    throw new ServiceUnitError('lifecycle_owner_unreadable');
  }
  if (text === undefined) return undefined;
  let record: Partial<OwnerRecord>;
  try {
    record = JSON.parse(text) as Partial<OwnerRecord>;
  } catch {
    throw new ServiceUnitError('lifecycle_owner_unreadable');
  }
  if (record.version !== 1 || typeof record.owner !== 'string' || !OWNER_PATTERN.test(record.owner) || typeof record.service !== 'string') {
    throw new ServiceUnitError('lifecycle_owner_unreadable');
  }
  return { owner: record.owner, service: record.service };
}

/**
 * Runs `operation` holding the cross-process `service-lifecycle` mutation
 * gate (`util/path-mutation-gate.ts`): one per user, with no target path,
 * like the per-user namespace of the service manager it guards. Every
 * owner-record mutation reads, compares and writes inside one hold, so a
 * remove or replace acts on the record this process read and never on a
 * successor's. It is never the `store` gate: a managed install holds this one
 * while it waits for the daemon it starts, and that daemon takes `store`.
 * Local-state relocation takes this gate before `store`, so the order is
 * always `service-lifecycle` then `store`. A held gate fails at once with
 * `lifecycle_owner_busy`; the gate frees itself when its holder process exits.
 *
 * @internal
 */
export async function withServiceOwnerGate<T>(operation: () => Promise<T>): Promise<T> {
  let gate;
  try {
    gate = await acquirePathMutationGate({ scope: 'service-lifecycle' }, { waitMs: 0 });
  } catch (error) {
    if (error instanceof PathMutationGateBusyError) throw new ServiceUnitError('lifecycle_owner_busy');
    throw error;
  }
  try {
    return await operation();
  } finally {
    await gate.release();
  }
}

/**
 * Records `owner` as the product's lifecycle owner. Idempotent for the same
 * owner; throws `lifecycle_owner_conflict` when another owner holds it and
 * `lifecycle_owner_busy` while another service lifecycle operation or a
 * local-state relocation is in progress. An App that sets autostart through its own mechanism (a login
 * item) claims here too, so the CLI's `install` refuses instead of adding a
 * second one.
 */
export async function claimServiceLifecycleOwner(input: ServiceLifecycleOwnerInput, fs: ServiceOwnerFs = fsp): Promise<void> {
  assertServiceOwner(input.owner);
  return withServiceOwnerGate(() => claimHeldServiceLifecycleOwner(input, fs));
}

/**
 * {@link claimServiceLifecycleOwner} for a caller already inside
 * {@link withServiceOwnerGate}.
 *
 * @internal
 */
export async function claimHeldServiceLifecycleOwner(input: ServiceLifecycleOwnerInput, fs: ServiceOwnerFs): Promise<void> {
  const current = await readServiceLifecycleOwner(input.storeDir, fs);
  if (current !== undefined && current.owner !== input.owner) throw new ServiceUnitError('lifecycle_owner_conflict');
  if (current?.service === input.service) return;
  const file = ownerRecordPath(input.storeDir);
  await fs.mkdir(path.dirname(file), { recursive: true, mode: 0o700 });
  const tmp = `${file}.${randomUUID()}.tmp`;
  const record: OwnerRecord = { version: 1, owner: input.owner, service: input.service };
  await fs.writeFile(tmp, `${JSON.stringify(record)}\n`, { encoding: 'utf8', mode: 0o600 });
  try {
    await fs.rename(tmp, file);
  } finally {
    await fs.rm(tmp, { force: true });
  }
}

/**
 * Removes the owner record when `owner` holds it; throws
 * `lifecycle_owner_conflict` when another owner does and `lifecycle_owner_busy`
 * while another service lifecycle operation or a local-state relocation is in
 * progress.
 */
export async function releaseServiceLifecycleOwner(input: Omit<ServiceLifecycleOwnerInput, 'service'>, fs: ServiceOwnerFs = fsp): Promise<void> {
  assertServiceOwner(input.owner);
  return withServiceOwnerGate(() => releaseHeldServiceLifecycleOwner(input, fs));
}

/**
 * {@link releaseServiceLifecycleOwner} for a caller already inside
 * {@link withServiceOwnerGate}.
 *
 * @internal
 */
export async function releaseHeldServiceLifecycleOwner(input: Omit<ServiceLifecycleOwnerInput, 'service'>, fs: ServiceOwnerFs): Promise<void> {
  const current = await readServiceLifecycleOwner(input.storeDir, fs);
  if (current === undefined) return;
  if (current.owner !== input.owner) throw new ServiceUnitError('lifecycle_owner_conflict');
  await fs.rm(ownerRecordPath(input.storeDir), { force: true });
}
