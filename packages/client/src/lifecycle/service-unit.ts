/**
 * Every unit this SDK generates carries this text (an XML comment in a
 * plist or WinSW descriptor, a `#` comment in a systemd unit). It is the
 * only ownership evidence `inspect()` accepts: a file at our unit path
 * without it is `foreign` and never changed, unless the operator passes
 * `install({ replaceUnmarked: true })`.
 */
export const SERVICE_UNIT_MARKER = 'byok-sdk-service-unit: generated by @byok-sdk/client; repair() reverts local edits';

/**
 * How an installed unit compares with the one this definition generates (#1097):
 *
 * - `absent`: no unit file at the unit path.
 * - `exact`: the unit and its launcher match byte for byte.
 * - `repairable`: the unit carries {@link SERVICE_UNIT_MARKER} but it, or
 *   its launcher, differs. `repair()` and `install()` rewrite both.
 * - `foreign`: a unit file without the marker. Nothing changes it.
 */
export type ServiceUnitState = 'absent' | 'exact' | 'repairable' | 'foreign';

export interface ServiceUnitInspection {
  state: ServiceUnitState;
  /** The plist, systemd unit, WinSW descriptor or Startup `.cmd`. */
  unitPath: string;
  /** The stable launcher the unit runs (macOS, Linux and a Windows `user` scope service); for WinSW the SCM runs the installed WinSW executable. */
  launcherPath: string;
  /** The lifecycle owner recorded in the store, when one is. */
  owner?: string;
}

export type ServiceRepairResult =
  | { status: 'repaired' }
  | { status: 'not-needed'; state: 'exact' | 'absent' };

const ERROR_MESSAGES = {
  service_unit_unmarked: 'A service unit this SDK did not generate exists at the unit path. Re-run install with replaceUnmarked (CLI: --replace-unmarked) to replace it, or remove it with the tool that installed it.',
  lifecycle_owner_conflict: 'Another lifecycle owner of this product manages autostart. Uninstall through that owner first.',
  lifecycle_owner_unreadable: 'The lifecycle owner record in the store cannot be read; preserve it for inspection.',
  lifecycle_owner_busy: 'Another service lifecycle operation or local-state relocation is in progress. Run it again when that one has finished.',
  invalid_owner: 'The lifecycle owner must be 1-32 characters: lowercase letters, digits and "-", starting with a letter or digit.',
  service_unload_timeout: 'The service manager did not finish unloading the stopped service in time. Check the service manager, then run the operation again.',
  service_stop_failed: 'The service stop program exited with a failure. The stop marker stays, so the service is not restarted; check the stop program, then run the operation again.',
  service_command_timeout: 'A platform command the service lifecycle ran did not finish in time; it was stopped. Whether it took effect is unknown. Check the service manager, then run the operation again.',
} as const;

export type ServiceUnitErrorCode = keyof typeof ERROR_MESSAGES;

/**
 * Closed codes only; the message never carries a path or OS text.
 *
 * `service_command_timeout` (#1971): a platform command a service lifecycle
 * or installation ran (`launchctl`, `systemctl`, WinSW, `sc.exe`, the Windows
 * Startup launch or launcher query, the Host's Windows stop program, or
 * `icacls` when an installation leases a store on Windows) outlived its
 * bound and was stopped. The service's state is UNKNOWN: the command may have taken
 * effect before it was stopped, so the error never means the change did
 * not happen. Read {@link ServiceUnitError.exitConfirmed} before running
 * the operation again.
 */
export class ServiceUnitError extends Error {
  /**
   * Set only with `service_command_timeout`. `true`: the timed-out command
   * (its process tree, or the Startup launch's own `cmd`) is proven to have
   * exited, so no part of it can still change the service. `false`: its
   * cleanup failed or did not finish in time, so it may still be running and
   * still change the service; a retry now can race it. The SDK keeps no
   * later ownership of that process. `cause` names the command, for
   * diagnostics only.
   */
  readonly exitConfirmed?: boolean;

  constructor(readonly code: ServiceUnitErrorCode, options?: ErrorOptions & { exitConfirmed?: boolean | undefined }) {
    super(ERROR_MESSAGES[code], options);
    this.name = 'ServiceUnitError';
    if (options?.exitConfirmed !== undefined) this.exitConfirmed = options.exitConfirmed;
  }
}

/**
 * Throws `error`, with an internal `PlatformCommandTimeoutError`, or the store
 * lease's `secure_dir_command_timeout` (#2116), as the public
 * `service_command_timeout`. The lifecycle and installation boundaries call
 * it; inside them the internal error stays. A timeout whose gate release
 * failed too arrives as the `AggregateError` of the timeout and the release
 * failures (#2002): it keeps that `AggregateError` as `cause`, and its
 * `exitConfirmed` comes from the timeout.
 *
 * @internal
 */
export function throwPublicCommandTimeout(error: unknown): never {
  const timeout = error instanceof AggregateError ? error.errors[0] : error;
  if (timeout instanceof PlatformCommandTimeoutError || (timeout instanceof SecureDirHardeningError && timeout.code === 'secure_dir_command_timeout')) {
    throw new ServiceUnitError('service_command_timeout', { cause: error, exitConfirmed: timeout.exitConfirmed });
  }
  throw error;
}

const OWNER_PATTERN = /^[a-z0-9][a-z0-9-]{0,31}$/u;

export function assertServiceOwner(owner: unknown): asserts owner is string {
  if (typeof owner !== 'string' || !OWNER_PATTERN.test(owner)) throw new ServiceUnitError('invalid_owner');
}

/** `<storeDir>/service`: the SDK-owned directory for the launcher and the lifecycle owner record. */
export function serviceStateDir(storeDir: string, platform: NodeJS.Platform = process.platform): string {
  return (platform === 'win32' ? path.win32 : path.posix).join(storeDir, 'service');
}

/** The stable launcher path a unit runs: a shell script on macOS and Linux, a batch file for a Windows `user` scope service. */
export function serviceLauncherPath(storeDir: string, serviceName: string, platform: NodeJS.Platform = process.platform): string {
  if (platform === 'win32') return path.win32.join(serviceStateDir(storeDir, platform), `${serviceName}.launcher.cmd`);
  return path.posix.join(serviceStateDir(storeDir, platform), `${serviceName}.launcher.sh`);
}

function shellQuote(value: string): string {
  if (hasControlChar(value)) {
    throw new Error(`service launcher values must not contain control characters (got ${JSON.stringify(value)})`);
  }
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

/**
 * The POSIX launcher every macOS and Linux unit runs. The unit names only
 * this file, so a new program (a moved binary, a new Node, a new `current`)
 * rewrites the launcher and never the unit. It sets no environment:
 * `byok-agent start --service` captures the login-shell environment at
 * start (#392).
 */
export function generateServiceLauncher(program: ServiceProgram): string {
  const lines = ['#!/bin/sh', `# ${SERVICE_UNIT_MARKER}`];
  if (program.cwd !== undefined) lines.push(`cd ${shellQuote(program.cwd)} || exit 1`);
  lines.push(`exec ${[program.command, ...program.args].map(shellQuote).join(' ')}`);
  return `${lines.join('\n')}\n`;
}

/**
 * One double-quoted `cmd.exe` word. `"` cannot be escaped inside a quoted
 * word and `%` expands even there, so either one, like a control character,
 * is refused rather than rewritten (#1337).
 *
 * @internal
 */
export function cmdQuote(value: string): string {
  if (hasControlChar(value) || /["%]/u.test(value)) {
    throw new Error(`Windows launcher values must not contain ", % or control characters (got ${JSON.stringify(value)})`);
  }
  return `"${value}"`;
}

/**
 * The batch launcher a Windows `user` scope unit starts (#1337). Each round
 * first ends with 0 when `stopMarker` exists, then `call`s the program: exit
 * 0 ends the launcher, any other exit reruns it about 10s later (the
 * exit-code contract in `exit-codes.ts`). The wait is `ping`, since
 * `timeout.exe` fails without console input. It sets no environment.
 */
export function generateWindowsUserLauncher(program: ServiceProgram, stopMarker: string): string {
  const lines = ['@echo off', `REM ${SERVICE_UNIT_MARKER}`];
  if (program.cwd !== undefined) lines.push(`cd /d ${cmdQuote(program.cwd)} || exit /b 1`);
  lines.push(
    ':run',
    `if exist ${cmdQuote(stopMarker)} exit /b 0`,
    `call ${[program.command, ...program.args].map(cmdQuote).join(' ')}`,
    'if %ERRORLEVEL% EQU 0 exit /b 0',
    'ping -n 11 127.0.0.1 >nul',
    'goto run',
  );
  return `${lines.join('\r\n')}\r\n`;
}

export interface ServiceUnitFile {
  path: string;
  content: string;
  mode?: number;
}

export type ServiceUnitFs = Pick<typeof fsp, 'readFile'>;

async function readOptional(fs: ServiceUnitFs, file: string): Promise<string | undefined> {
  try {
    return await fs.readFile(file, 'utf8');
  } catch (error) {
    if ((error as NodeJS.ErrnoException)?.code === 'ENOENT') return undefined;
    throw error;
  }
}

/** Compares the installed files with `expected`; `expected[0]` is the unit. */
export async function classifyServiceUnit(fs: ServiceUnitFs, expected: readonly ServiceUnitFile[]): Promise<ServiceUnitState> {
  const [unit, ...rest] = expected;
  if (!unit) throw new Error('classifyServiceUnit requires the unit file');
  const installed = await readOptional(fs, unit.path);
  if (installed === undefined) return 'absent';
  if (!installed.includes(SERVICE_UNIT_MARKER)) return 'foreign';
  if (installed !== unit.content) return 'repairable';
  for (const file of rest) {
    if ((await readOptional(fs, file.path)) !== file.content) return 'repairable';
  }
  return 'exact';
}

const OWNER_RECORD_FILENAME = 'lifecycle-owner.json';

export type ServiceRegistration =
  | { readonly manager: 'launchd'; readonly uid: number }
  | { readonly manager: 'systemd' | 'winsw' }
  | { readonly manager: 'windows-user'; readonly launcher: string };

interface OwnerRecord {
  version: 1;
  owner: string;
  service: string;
  registration?: ServiceRegistration;
}

export interface ServiceLifecycleOwnerInput {
  storeDir: string;
  /** Who sets autostart for this product, e.g. `cli` or `app`. */
  owner: string;
  /** The service name the owner registers. */
  service: string;
}

export type ServiceOwnerFs = Pick<typeof fsp, 'readFile' | 'writeFile' | 'rename' | 'rm' | 'mkdir'>;

function ownerRecordPath(storeDir: string): string {
  return path.join(serviceStateDir(storeDir), OWNER_RECORD_FILENAME);
}

/**
 * The lifecycle owner recorded for this product's store (#1097): the one
 * party (the CLI, or the product's App) that sets autostart. Undefined when
 * no owner holds it.
 */
export async function readServiceLifecycleOwner(storeDir: string, fs: ServiceOwnerFs = fsp): Promise<{ owner: string; service: string } | undefined> {
  const record = await readOwnerRecord(storeDir, fs);
  return record === undefined ? undefined : { owner: record.owner, service: record.service };
}

async function readOwnerRecord(storeDir: string, fs: ServiceUnitFs): Promise<OwnerRecord | undefined> {
  try {
    const text = await readOptional(fs, ownerRecordPath(storeDir));
    return text === undefined ? undefined : parseOwnerRecord(text);
  } catch {
    throw new ServiceUnitError('lifecycle_owner_unreadable');
  }
}

function parseOwnerRecord(text: string): OwnerRecord {
  const record = JSON.parse(text) as OwnerRecord | null;
  if (record?.version !== 1 || typeof record.owner !== 'string' || !OWNER_PATTERN.test(record.owner) || typeof record.service !== 'string') {
    throw new ServiceUnitError('lifecycle_owner_unreadable');
  }
  const registration = record.registration;
  if (registration !== undefined && !validRegistration(registration)) throw new ServiceUnitError('lifecycle_owner_unreadable');
  return record;
}

function validRegistration(value: ServiceRegistration): boolean {
  switch (value?.manager) {
    case 'launchd': return Number.isSafeInteger(value.uid) && value.uid >= 0;
    case 'systemd':
    case 'winsw': return true;
    case 'windows-user': return typeof value.launcher === 'string' && path.win32.isAbsolute(value.launcher) && !hasControlChar(value.launcher);
    default: return false;
  }
}

/** Inspect an owner record without following symlinks or blocking on a special file. @internal */
export async function inspectServiceOwnerRecord(storeDir: string): Promise<OwnerRecord | undefined> {
  const file = ownerRecordPath(storeDir);
  const dir = await fsp.lstat(path.dirname(file)).catch((error: NodeJS.ErrnoException) => {
    if (error.code !== 'ENOENT') throw error;
    return undefined;
  });
  if (dir === undefined) return undefined;
  if (!dir.isDirectory()) throw new ServiceUnitError('lifecycle_owner_unreadable');
  const named = await fsp.lstat(file).catch((error: NodeJS.ErrnoException) => {
    if (error.code !== 'ENOENT') throw error;
    return undefined;
  });
  if (named === undefined) return undefined;
  if (!named.isFile()) throw new ServiceUnitError('lifecycle_owner_unreadable');
  const handle = await fsp.open(file, fsConstants.O_RDONLY | (fsConstants.O_NONBLOCK ?? 0) | (fsConstants.O_NOFOLLOW ?? 0));
  try {
    const opened = await handle.stat();
    if (!opened.isFile() || named.dev !== opened.dev || named.ino !== opened.ino || opened.size > 8192) {
      throw new ServiceUnitError('lifecycle_owner_unreadable');
    }
    const buffer = Buffer.alloc(opened.size);
    const { bytesRead } = await handle.read(buffer, 0, buffer.length, 0);
    const after = await fsp.lstat(file);
    if (!after.isFile() || after.dev !== opened.dev || after.ino !== opened.ino || after.size !== opened.size || after.mtimeMs !== opened.mtimeMs || bytesRead !== buffer.length) {
      throw new ServiceUnitError('lifecycle_owner_unreadable');
    }
    return parseOwnerRecord(buffer.toString('utf8'));
  } finally {
    await handle.close();
  }
}

/**
 * Runs `operation` holding the cross-process `service-lifecycle` mutation
 * gate (`util/path-mutation-gate.ts`): one per user, with no target path,
 * like the per-user namespace of the service manager it guards. Every
 * owner-record mutation reads, compares and writes inside one hold, so a
 * remove or replace acts on the record this process read and never on a
 * successor's. It is never the `store` gate: a managed install holds this one
 * while it waits for the daemon it starts, and that daemon takes `store`.
 * Local-state relocation takes this gate before `store`, so the order is
 * always `service-lifecycle` then `store`. A held gate fails at once with
 * `lifecycle_owner_busy`; the gate frees itself when its holder process exits.
 * `gateRoot` is the lifecycle option of that name.
 *
 * @internal
 */
export async function withServiceOwnerGate<T>(operation: () => Promise<T>, gateRoot?: string): Promise<T> {
  let gate;
  try {
    gate = await acquirePathMutationGate({ scope: 'service-lifecycle' }, { waitMs: 0, ...(gateRoot === undefined ? {} : { gateRoot }) });
  } catch (error) {
    if (error instanceof PathMutationGateBusyError) throw new ServiceUnitError('lifecycle_owner_busy');
    throw error;
  }
  let result: T;
  try {
    result = await operation();
  } catch (error) {
    const failures: unknown[] = [];
    await gate.release().catch((releaseError: unknown) => { failures.push(releaseError); });
    // A ServiceUnitError keeps its class and code, as a busy gate error does (#2002).
    if (failures.length > 0 && error instanceof ServiceUnitError) {
      throw new ServiceUnitError(error.code, { cause: new AggregateError([error, ...failures], `${error.message}; releasing the service-lifecycle gate failed too`), exitConfirmed: error.exitConfirmed });
    }
    throw withGateReleaseFailures(error, failures);
  }
  await gate.release();
  return result;
}

/**
 * Records `owner` as the product's lifecycle owner. Idempotent for the same
 * owner; throws `lifecycle_owner_conflict` when another owner holds it and
 * `lifecycle_owner_busy` while another service lifecycle operation or a
 * local-state relocation is in progress. An App that sets autostart through its own mechanism (a login
 * item) claims here too, so the CLI's `install` refuses instead of adding a
 * second one.
 */
export async function claimServiceLifecycleOwner(input: ServiceLifecycleOwnerInput, fs: ServiceOwnerFs = fsp): Promise<void> {
  assertServiceOwner(input.owner);
  return withServiceOwnerGate(() => claimHeldServiceLifecycleOwner(input, fs));
}

/**
 * {@link claimServiceLifecycleOwner} for a caller already inside
 * {@link withServiceOwnerGate}.
 *
 * @internal
 */
export async function claimHeldServiceLifecycleOwner(input: ServiceLifecycleOwnerInput, fs: ServiceOwnerFs, registration?: ServiceRegistration): Promise<void> {
  const current = await readOwnerRecord(input.storeDir, fs);
  if (current !== undefined && current.owner !== input.owner) throw new ServiceUnitError('lifecycle_owner_conflict');
  if (current?.service === input.service && (registration === undefined || isDeepStrictEqual(registration, current.registration))) return;
  if (registration !== undefined && !validRegistration(registration)) throw new ServiceUnitError('lifecycle_owner_unreadable');
  const file = ownerRecordPath(input.storeDir);
  await fs.mkdir(path.dirname(file), { recursive: true, mode: 0o700 });
  const tmp = `${file}.${randomUUID()}.tmp`;
  const record: OwnerRecord = { version: 1, owner: input.owner, service: input.service, ...(registration === undefined ? {} : { registration }) };
  await fs.writeFile(tmp, `${JSON.stringify(record)}\n`, { encoding: 'utf8', mode: 0o600 });
  try {
    await fs.rename(tmp, file);
  } finally {
    await fs.rm(tmp, { force: true });
  }
}

/**
 * Removes the owner record when `owner` holds it; throws
 * `lifecycle_owner_conflict` when another owner does and `lifecycle_owner_busy`
 * while another service lifecycle operation or a local-state relocation is in
 * progress.
 */
export async function releaseServiceLifecycleOwner(input: Omit<ServiceLifecycleOwnerInput, 'service'>, fs: ServiceOwnerFs = fsp): Promise<void> {
  assertServiceOwner(input.owner);
  return withServiceOwnerGate(() => releaseHeldServiceLifecycleOwner(input, fs));
}

/**
 * {@link releaseServiceLifecycleOwner} for a caller already inside
 * {@link withServiceOwnerGate}.
 *
 * @internal
 */
export async function releaseHeldServiceLifecycleOwner(input: Omit<ServiceLifecycleOwnerInput, 'service'>, fs: ServiceOwnerFs): Promise<void> {
  const current = await readServiceLifecycleOwner(input.storeDir, fs);
  if (current === undefined) return;
  if (current.owner !== input.owner) throw new ServiceUnitError('lifecycle_owner_conflict');
  await fs.rm(ownerRecordPath(input.storeDir), { force: true });
}
