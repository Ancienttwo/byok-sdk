import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { findEnvKeys } from '@earendil-works/pi-ai/compat';
import { getBuiltinProviders } from '@earendil-works/pi-ai/providers/all';

// Projects the pinned pi's provider credential env names into a checked-in,
// import-free constant, so the adapters entry carries the names without
// importing pi. `node scripts/generate-pi-provider-env.mjs` rewrites it;
// `--check` writes nothing and exits 1 when the file no longer matches the
// pinned pi.
const target = fileURLToPath(new URL('../src/adapters/pi/pi-provider-env.generated.ts', import.meta.url));
// pi-ai does not export its manifest; find it above the resolved entry.
let manifestDir = path.dirname(fileURLToPath(import.meta.resolve('@earendil-works/pi-ai/compat')));
while (!existsSync(path.join(manifestDir, 'package.json'))) manifestDir = path.dirname(manifestDir);
const piAiVersion = JSON.parse(readFileSync(path.join(manifestDir, 'package.json'), 'utf8')).version;

// An environment that answers every name makes `findEnvKeys` return every
// candidate name of a provider.
const everyName = new Proxy({}, { get: (_target, key) => (typeof key === 'string' ? 'present' : undefined) });
const byProvider = Object.fromEntries(
  getBuiltinProviders().map((id) => [id, [...(findEnvKeys(id, everyName) ?? [])].sort()]).sort(([a], [b]) => (a < b ? -1 : 1)),
);
const names = [...new Set(Object.values(byProvider).flat())].sort();
if (names.length === 0) throw new Error('pinned pi reports no provider credential env names');

const quoted = (list) => list.map((name) => `'${name}'`).join(', ');
const source = [
  `// GENERATED by scripts/generate-pi-provider-env.mjs from pi-ai ${piAiVersion}. Do not edit.`,
  '// Provider id to the credential env names the pinned pi reads for it.',
  'export const PI_PROVIDER_ENV_KEYS: Readonly<Record<string, readonly string[]>> = Object.freeze({',
  ...Object.entries(byProvider).map(([id, list]) => `  '${id}': [${quoted(list)}],`),
  '});',
  '',
  '// The sorted union of every name above.',
  'export const PI_PROVIDER_ENV_KEY_NAMES: readonly string[] = Object.freeze([',
  ...names.map((name) => `  '${name}',`),
  ']);',
  '',
].join('\n');

if (process.argv.includes('--check')) {
  let current;
  try { current = readFileSync(target, 'utf8'); } catch { current = undefined; }
  if (current !== source) {
    console.error('pi-provider-env.generated.ts is stale; run node scripts/generate-pi-provider-env.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(target, source);
}
